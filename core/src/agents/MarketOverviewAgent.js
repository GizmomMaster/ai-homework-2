import { TextAgent } from "./TextAgent.js";

/**
 * Температура комментария к рынку. Не ноль: пара фраз о том, что происходило,
 * при нулевой температуре выходит одинаковой изо дня в день. Но и не 0.3, как
 * у сведения отчёта: здесь нужна верность цифрам, а не живость слога.
 */
export const OVERVIEW_TEMPERATURE = 0.2;

/**
 * Системный промпт агента комментария к рынку.
 *
 * Модель пишет **только текст** — таблицы собирает код. Разделение появилось
 * не из принципа, а из наблюдения: локальная модель раз за разом промахивалась
 * мимо формата — то ставила markdown-таблицу, которую Telegram не рисует, то
 * клала в блок кода заголовок и фразу вместо таблицы. Каждый такой промах
 * стоил всей сводки: показать пользователю сломанную таблицу нельзя, и в ход
 * шёл шаблон целиком, вместе с той частью, которую модель написала хорошо.
 *
 * Теперь ломаться нечему. Выравнивание колонок — работа для кода, который
 * считает пробелы; увидеть в цифрах картину и сказать о ней словами — работа
 * для модели. Каждый занят тем, что умеет.
 */
export const OVERVIEW_PROMPT = `Ты — аналитик в ассистенте для криптотрейдеров. Тебе дают итоги прошедших суток по топ-монетам рынка. Напиши короткий комментарий к ним — его покажут пользователю над таблицей с этими же цифрами.

ЧТО НАПИСАТЬ:
* Две-три фразы о том, что происходило: рынок рос или падал в целом, кто выбился из общей картины и насколько.
* Называй тикеры и проценты, но не пересказывай таблицу построчно — она будет прямо под твоим текстом, и повторять её незачем.
* Если движение разнонаправленное, так и скажи: «рынок разошёлся» честнее, чем натянутый общий вывод.

ЧЕГО НЕ ДЕЛАТЬ:
* **Никаких таблиц, списков, блоков кода и заголовков.** Только связный текст в один абзац. Таблицу нарисуют без тебя, и твоя разметка ей помешает.
* Не используй чисел, которых нет во входных данных, и не пересчитывай данные. Выдуманное число среди настоящих неотличимо от измеренного, а проверить его пользователю негде.
* Не давай торговых рекомендаций и не предсказывай движение цены. Опиши, что показывают данные, — решение принимает пользователь.
* Без вступлений вроде «конечно» и «вот комментарий» — сразу по делу.`;

/**
 * Агент комментария к сводке по рынку.
 *
 * Историю диалога не видит — по той же причине, что и `SummaryAgent`: она
 * подсунула бы модели числа из прошлых сводок, а спутать их с сегодняшними
 * ничего не мешает.
 */
export class MarketOverviewAgent extends TextAgent {
  /** @param {{ llmRunner: import("../llm/LlmRunner.js").LlmRunner }} deps */
  constructor({ llmRunner }) {
    super({ llmRunner, systemPrompt: OVERVIEW_PROMPT, temperature: OVERVIEW_TEMPERATURE });
  }

  /**
   * @param {object} overview результат `buildMarketOverview`
   * @returns {Promise<import("../llm/LlmRunner.js").ChatResult>}
   */
  async comment(overview) {
    return this.answer([{ role: "user", content: buildBrief(overview) }]);
  }
}

const MONTHS = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
];

/**
 * Задание для модели.
 *
 * Числа приезжают сюда **уже отформатированными**. Округление — арифметика, а
 * арифметика на модели худший из способов её выполнить (см. `compactForPrompt`):
 * переокруглив, модель тихо разойдётся с цифрами в таблице под своим же
 * текстом, и расхождение будет видно пользователю невооружённым глазом.
 */
export function buildBrief(overview) {
  const rows = overview.coins.map((coin) =>
    [
      coin.symbol,
      `за сутки ${percent(coin.changePercent)}`,
      `объём ${money(coin.dayVolume)}`,
      `сейчас ${price(coin.price)}`,
      `за 24ч ${percent(coin.priceChangePercent24h)}`,
      `капитализация ${money(coin.marketCap)}`,
    ].join(" | "),
  );

  return [
    `ПРОШЕДШИЕ СУТКИ: ${formatDate(overview.dayStartMs)} (UTC)`,
    `ДАННЫЕ (значения готовы к печати, не пересчитывай):\n${rows.join("\n")}`,
    "Проценты за сутки — за календарные сутки UTC, за 24ч — за скользящие " +
      "сутки от текущего момента. Это разные окна; если ссылаешься на них, не путай.",
  ].join("\n\n");
}

/** Форматирование то же, что у таблицы, — иначе текст разойдётся с ней в цифрах. */
function price(value) {
  if (value === null || value === undefined) return "н/д";
  if (value >= 1) return value.toFixed(2);
  if (value >= 0.01) return value.toFixed(4);
  return value.toPrecision(4);
}

function percent(value) {
  if (value === null || value === undefined) return "н/д";
  return `${value >= 0 ? "+" : ""}${value.toFixed(2)}%`;
}

function money(value) {
  if (value === null || value === undefined) return "н/д";
  const units = [
    [1e12, "T"],
    [1e9, "B"],
    [1e6, "M"],
    [1e3, "K"],
  ];
  for (const [scale, suffix] of units) {
    if (value >= scale) {
      const scaled = value / scale;
      return `$${scaled >= 100 ? scaled.toFixed(0) : scaled.toFixed(scaled >= 10 ? 1 : 2)}${suffix}`;
    }
  }
  return `$${value.toFixed(0)}`;
}

function formatDate(ms) {
  const date = new Date(ms);
  return `${date.getUTCDate()} ${MONTHS[date.getUTCMonth()]} ${date.getUTCFullYear()}`;
}
