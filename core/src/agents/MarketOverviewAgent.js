import { TextAgent } from "./TextAgent.js";

/**
 * Температура сводки по рынку. Ниже, чем у сведения отчёта (0.3): там модель
 * отвечает на вопрос и живая формулировка уместна, здесь — печатает таблицу,
 * и разнообразие в ней означает разъехавшиеся колонки.
 */
export const OVERVIEW_TEMPERATURE = 0.2;

/**
 * Системный промпт агента сводки по рынку.
 *
 * Главное требование — блоки кода. Telegram не поддерживает таблицы **ни в
 * markdown, ни в HTML**: markdown-таблица приедет пользователю сырым текстом
 * с палками, а пропорциональный шрифт разведёт колонки. Моноширинный шрифт
 * есть только внутри блока кода, поэтому запрет на markdown-таблицы здесь не
 * стилистический совет, а условие читаемости.
 *
 * Образец в промпте приведён целиком и не случайно: формат, показанный
 * примером, модель воспроизводит заметно надёжнее, чем формат, описанный
 * словами, — особенно когда речь о выравнивании пробелами.
 */
export const OVERVIEW_PROMPT = `Ты — аналитик в ассистенте для криптотрейдеров. Тебе дают данные по топ-монетам рынка: итоги прошедших суток и текущее состояние. Твоя задача — оформить их в сводку для пользователя мессенджера.

СТРУКТУРА ОТВЕТА, ровно в этом порядке:
1. Заголовок с датой прошедших суток.
2. Одна-две фразы о том, что происходило: рынок рос или падал в целом, кто выделяется.
3. Таблица итогов суток внутри блока кода.
4. Подзаголовок «Сейчас» и таблица текущего состояния внутри блока кода.
5. Сноски курсивом: что отфильтровано и чем отличаются два столбца процентов.
6. Подзаголовок «Что можно спросить» и 5–6 примеров запросов.

ТАБЛИЦЫ:
* Только внутри блоков кода — три обратные кавычки до и после. Markdown-таблицы с палками запрещены: мессенджер их не рисует, пользователь увидит месиво.
* **В блоке кода не должно быть ничего, кроме самой таблицы.** Ни заголовка, ни даты, ни фраз о происходящем на рынке, ни пустых строк перед строкой заголовков колонок. Всё это — обычный текст снаружи блока. Блок кода нужен ровно за одним: внутри него моноширинный шрифт, и только он держит колонки ровными. Текст, набранный как код, читателю не помогает, а таблицы он при этом не получает вовсе.
* Блоков кода в ответе ровно два — по одному на таблицу. Первая строка каждого блока — заголовки колонок, дальше по строке на монету.
* Колонки выравнивай пробелами: числа по правому краю, тикеры по левому. Каждый столбец одной ширины во всех строках, включая заголовок.
* Ширина строки — не больше 44 знаков, иначе на телефоне поедет прокрутка.

Образец таблицы, держись этого вида:
\`\`\`
МОНЕТА       ОТКР      ЗАКР     Δ%   ОБЪЁМ
BTC      80249.59  77845.87  -3.00  $1.56B
DOGE       0.0872    0.0851  -2.35   $342M
\`\`\`

ЧИСЛА:
* Все значения уже посчитаны и округлены — печатай их ровно так, как они даны. Ничего не пересчитывай и не переокругляй: расхождение с исходными данными пользователю проверить негде.
* Не добавляй чисел, которых нет во входных данных.
* Где написано «н/д», так и печатай — данные собрать не удалось.

ЧЕГО НЕ ДЕЛАТЬ:
* Не давай торговых рекомендаций и не предсказывай движение цены. Опиши, что показывают данные.
* Без вступлений вроде «конечно» и «вот сводка» — начинай с заголовка.
* Тикеры с подчёркиванием (например FIGR_HELOC) вне блоков кода бери в одинарные обратные кавычки: иначе подчёркивание сломает разметку.`;

/**
 * Агент сводки по рынку: превращает собранные данные в готовое сообщение.
 *
 * Историю диалога не видит — по той же причине, что и `SummaryAgent`: она
 * подсунула бы модели числа из прошлых сводок, а спутать их с сегодняшними
 * ничего не мешает.
 */
export class MarketOverviewAgent extends TextAgent {
  /** @param {{ llmRunner: import("../llm/LlmRunner.js").LlmRunner }} deps */
  constructor({ llmRunner }) {
    super({ llmRunner, systemPrompt: OVERVIEW_PROMPT, temperature: OVERVIEW_TEMPERATURE });
  }

  /**
   * @param {object} overview результат `buildMarketOverview`
   * @returns {Promise<import("../llm/LlmRunner.js").ChatResult>}
   */
  async compose(overview) {
    return this.answer([{ role: "user", content: buildBrief(overview) }]);
  }
}

const MONTHS = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
];

/**
 * Задание для модели.
 *
 * Числа приезжают сюда **уже отформатированными**, и это не попытка сделать
 * работу за модель. Округление — арифметика, а арифметика на модели худший из
 * способов её выполнить (см. `compactForPrompt`): переокруглив, модель тихо
 * разойдётся с настоящими данными, и проверить это пользователю неоткуда.
 * К тому же в таблице от округления зависит ширина колонки — разнобой в
 * знаках после запятой ломает выравнивание вернее, чем что-либо ещё.
 *
 * Модели остаётся то, что она и должна делать: разложить это по колонкам,
 * увидеть в цифрах картину и написать про неё словами.
 */
export function buildBrief(overview) {
  const rows = overview.coins.map((coin) =>
    [
      coin.symbol,
      `откр ${price(coin.open)}`,
      `закр ${price(coin.close)}`,
      `Δ ${percent(coin.changePercent)}`,
      `объём ${money(coin.dayVolume)}`,
      `сейчас ${price(coin.price)}`,
      `Δ24ч ${percent(coin.priceChangePercent24h)}`,
      `объём24ч ${money(coin.volume24h)}`,
      `капитализация ${money(coin.marketCap)}`,
    ].join(" | "),
  );

  const parts = [
    `ПРОШЕДШИЕ СУТКИ: ${formatDate(overview.dayStartMs)} (UTC)`,
    `ДАННЫЕ (значения готовы к печати, не пересчитывай):\n${rows.join("\n")}`,
  ];

  const excluded = [...overview.excluded.stablecoins, ...overview.excluded.wrapped];
  if (excluded.length > 0) {
    parts.push(
      `ИСКЛЮЧЕНО ИЗ РЕЙТИНГА: стейблкоины (${overview.excluded.stablecoins.join(", ") || "нет"}), ` +
        `обёртки и стейкинг-деривативы (${overview.excluded.wrapped.join(", ") || "нет"}). ` +
        "Упомяни это сноской: пользователь должен понимать, почему в списке нет USDT.",
    );
  }

  const fallback = overview.coins.filter((c) => c.source === "coingecko").map((c) => c.symbol);
  if (fallback.length > 0) {
    parts.push(
      `НЕТ ПАРЫ НА БИРЖЕ, СУТКИ ПОСЧИТАНЫ ПО CoinGecko: ${fallback.join(", ")}. Отметь это сноской.`,
    );
  }

  parts.push(
    "ПОЯСНЕНИЕ ДЛЯ СНОСКИ: Δ% — за календарные сутки UTC, Δ24ч — за скользящие " +
      "сутки от текущего момента. Это разные окна, и расхождение между ними — не ошибка.",
  );

  return parts.join("\n\n");
}

/** Форматирование — то же, что у отката, чтобы вид сводки не зависел от того, кто её собрал. */
function price(value) {
  if (value === null || value === undefined) return "н/д";
  if (value >= 1) return value.toFixed(2);
  if (value >= 0.01) return value.toFixed(4);
  return value.toPrecision(4);
}

function percent(value) {
  if (value === null || value === undefined) return "н/д";
  return `${value >= 0 ? "+" : ""}${value.toFixed(2)}%`;
}

function money(value) {
  if (value === null || value === undefined) return "н/д";
  const units = [
    [1e12, "T"],
    [1e9, "B"],
    [1e6, "M"],
    [1e3, "K"],
  ];
  for (const [scale, suffix] of units) {
    if (value >= scale) {
      const scaled = value / scale;
      return `$${scaled >= 100 ? scaled.toFixed(0) : scaled.toFixed(scaled >= 10 ? 1 : 2)}${suffix}`;
    }
  }
  return `$${value.toFixed(0)}`;
}

function formatDate(ms) {
  const date = new Date(ms);
  return `${date.getUTCDate()} ${MONTHS[date.getUTCMonth()]} ${date.getUTCFullYear()}`;
}
