import { TextAgent } from "./TextAgent.js";
import { compactForPrompt } from "../domain/compactForPrompt.js";

/**
 * Температура сведения отчёта. Ниже, чем у теоретических ответов: там нужна
 * живая речь, здесь — верность цифрам. Совсем в ноль не уводим, иначе текст
 * получается канцелярским и одинаковым от запроса к запросу.
 */
export const SUMMARY_TEMPERATURE = 0.3;

/**
 * Системный промпт сводящего агента.
 *
 * Запрет выдумывать числа здесь строже, чем в теоретической ветке, и по
 * серьёзной причине: отчёт выглядит подкреплённым данными. Выдуманное число
 * среди настоящих читается как измеренное, и проверить его пользователю
 * неоткуда.
 */
export const SUMMARY_PROMPT = `Ты — аналитик в ассистенте для криптотрейдеров. Тебе дают вопрос пользователя и данные, собранные с биржи по этому вопросу. Твоя задача — написать по ним короткий отчёт.

КАК ПИСАТЬ:
* По-русски, сразу по делу, без вступлений вроде «конечно» и «вот отчёт».
* Начни с ответа на заданный вопрос, а не с перечисления данных. Если просили сравнить — сравни и скажи, кто больше и во сколько раз.
* Приводи ключевые числа в тексте, а не отдельным списком. Крупные суммы округляй до понятного: 1 405 120 787 — это «1.4 млрд».
* Один-три абзаца. Разметка Markdown умеренная: **жирный** для тикеров и главных чисел. Заголовки и таблицы не нужны — читают в мессенджере.

ЧЕГО НЕ ДЕЛАТЬ:
* Не используй никаких чисел, кроме тех, что даны во входных данных. Не оценивай, не округляй до неузнаваемости, не достраивай недостающее по памяти. Выдуманное число среди настоящих неотличимо от измеренного, а проверить его пользователю негде.
* Если какие-то данные собрать не удалось, скажи об этом прямо одной фразой и не делай вид, что вывод полный.
* Не давай торговых рекомендаций и не предсказывай движение цены. Опиши, что показывают данные, — решение принимает пользователь.`;

/**
 * Агент сведения отчёта: превращает результаты вызовов инструментов в связный
 * ответ на вопрос пользователя.
 *
 * Историю диалога намеренно не видит. Она удлинила бы промпт и, что хуже,
 * подсунула бы модели числа из прошлых отчётов — а спутать их с нынешними
 * ничего не мешает.
 */
export class SummaryAgent extends TextAgent {
  /** @param {{ llmRunner: import("../llm/LlmRunner.js").LlmRunner }} deps */
  constructor({ llmRunner }) {
    super({ llmRunner, systemPrompt: SUMMARY_PROMPT, temperature: SUMMARY_TEMPERATURE });
  }

  /**
   * @param {{
   *   question: string,
   *   taskSummary: string,
   *   steps: Array<{ action: string, ok: boolean, value?: object, error?: { code: string, message?: string } }>,
   * }} input
   * @returns {Promise<import("../llm/LlmRunner.js").ChatResult>}
   */
  async summarize({ question, taskSummary, steps }) {
    return this.answer([{ role: "user", content: buildBrief({ question, taskSummary, steps }) }]);
  }
}

/**
 * Одна и та же величина под разными именами в ответах разных инструментов.
 * `get_crypto_current_price` и `get_crypto_24h_ticker_stats` по одному
 * символу частично пересекаются по смыслу (текущая цена, суточное
 * изменение, суточный максимум/минимум) — но Binance называет их в двух
 * эндпоинтах по-разному, поэтому пересечение не поймать сравнением по
 * имени поля, только по значению после приведения имени к общему виду.
 * Значение при этом остаётся под тем именем, которым его назвал первый
 * увидевший его шаг, — второе имя просто не добавляется.
 */
const FIELD_ALIASES = {
  lastPrice: "price",
  priceChangePercent: "priceChangePercent24h",
  high: "high24h",
  low: "low24h",
};

/**
 * Убирает из результатов шагов поля, значение которых по той же монете уже
 * показано более ранним шагом — в том числе под другим именем (см.
 * FIELD_ALIASES). Планировщик не обязан думать о таких пересечениях между
 * инструментами: если оба шага попали в план, `SummaryAgent` иначе показал
 * бы модели одно и то же число дважды.
 *
 * Дедуп применяется только к примитивным полям: `symbol` никогда не
 * трогаем (иначе непонятно, к какой монете относится остаток полей), а
 * сложные значения (массивы свечей и т.п.) сравнением по `===` не поймать —
 * и не нужно, для них это уже делает compactForPrompt.
 *
 * @param {Array<{ ok: boolean, value?: object }>} steps
 */
export function dedupeStepValues(steps) {
  const seen = new Map();

  return steps.map((step) => {
    if (!step.ok || step.value === null || typeof step.value !== "object") return step;
    const { symbol } = step.value;
    if (!symbol) return step;

    const value = {};
    for (const [key, item] of Object.entries(step.value)) {
      const dedupeKey = `${symbol}:${FIELD_ALIASES[key] ?? key}`;
      if (key !== "symbol" && seen.has(dedupeKey) && seen.get(dedupeKey) === item) continue;
      value[key] = item;
      seen.set(dedupeKey, item);
    }
    return { ...step, value };
  });
}

/**
 * Задание для модели: вопрос, задача и собранные данные. Неудачные шаги
 * перечисляются наравне с удачными — модель должна знать, чего не хватает,
 * иначе оговорка о неполноте в отчёт не попадёт.
 */
export function buildBrief({ question, taskSummary, steps }) {
  const deduped = dedupeStepValues(steps);

  // JSON без отступов. Отступы модель не читает — их роль в том, чтобы JSON
  // разбирал глазами человек, — а платим за них мы: перевод строки и пробел
  // на каждое поле дают 13% длины на плоском объекте вроде котировки и 23%
  // на вложенном (выборка свечей, строки скринера), и это самая большая
  // часть промпта сводящего агента: у него константа всего ~390 токенов
  // против ~690 на данные шагов.
  const collected = deduped
    .filter((step) => step.ok)
    .map((step) => `${step.action}:\n${JSON.stringify(compactForPrompt(step.value))}`)
    .join("\n\n");

  // Вместе с причиной: отказ инструмента бывает содержательным ответом, а не
  // просто неудачей. «RSI считается только для BTC и ETH» — это то, что
  // пользователь и должен прочитать; без причины модель напишет размытое «не
  // удалось получить данные» и подменит ответ отговоркой.
  const missing = deduped
    .filter((step) => !step.ok)
    .map((step) => (step.error?.message ? `- ${step.action}: ${step.error.message}` : `- ${step.action}`))
    .join("\n");

  const parts = [
    `ВОПРОС ПОЛЬЗОВАТЕЛЯ: ${question}`,
    `ЗАДАЧА: ${taskSummary}`,
    `СОБРАННЫЕ ДАННЫЕ:\n${collected || "нет"}`,
  ];
  if (missing) parts.push(`ДАННЫЕ, КОТОРЫЕ СОБРАТЬ НЕ УДАЛОСЬ:\n${missing}`);

  return parts.join("\n\n");
}
