/**
 * Оценка размера текста в токенах — для реплик, которых модель не считала.
 *
 * Размер диалога мы обычно не оцениваем, а берём готовым: раннер возвращает
 * `promptTokens` за весь промпт целиком, и это точная величина. Но в ветке
 * задачи текст ответа собирается у нас (отчёт по данным биржи, объяснение
 * планировщика), а сводящий агент считает свой собственный промпт — данные
 * шагов, а не историю диалога. Измерить обмен нечем, пока в диалог не придёт
 * следующий вопрос к отвечающему агенту.
 *
 * Раньше в этом случае счётчик просто не двигался, и это была не осторожность,
 * а потеря: диалог из одних задач рос историей, а числился пустым — «16000 из
 * 16000» под каждым отчётом. Оценка грубая, но она хотя бы одного порядка с
 * правдой, и первый же измеренный вызов заменяет её точным числом.
 *
 * Ошибаться безопаснее в большую сторону, поэтому знаков на токен взято три,
 * а не четыре: кириллица у используемых токенизаторов идёт примерно по 2.5–3.5
 * знака, таблицы и числа отчёта — по 3–4. Недооценка означала бы, что мы не
 * попросим начать новый диалог вовремя, а LM Studio молча обрежет начало
 * истории (см. `LmStudioRunner`); переоценка — что попросим на пару реплик
 * раньше, чем было необходимо.
 */
const CHARS_PER_TOKEN = 3;

/**
 * Разметка роли и разделители, в которые раннер оборачивает каждое сообщение:
 * в самом тексте их нет, а в промпт они попадают.
 */
const MESSAGE_OVERHEAD_TOKENS = 4;

/**
 * @param {...string} texts реплики обмена
 * @returns {number} во сколько токенов они примерно обойдутся в промпте
 */
export function estimateExchangeTokens(...texts) {
  return texts.reduce(
    (sum, text) => sum + Math.ceil((text?.length ?? 0) / CHARS_PER_TOKEN) + MESSAGE_OVERHEAD_TOKENS,
    0,
  );
}
